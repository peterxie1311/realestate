/*
  Run this in pgAdmin's Query Tool.

  Change selected_schema below if the application objects are not in public.
  The query returns one row and one column named schema_ddl. Copy or download
  that cell and send it back for review/commit under sql/schema.

  This is intended as a readable schema snapshot. pg_dump --schema-only is
  still the authoritative option for complex dependency graphs, extensions,
  ownership, grants, partitioning, and every PostgreSQL-specific detail.
*/

WITH RECURSIVE
params AS (
    SELECT 'public'::name AS selected_schema
),
ddl_parts AS (
    SELECT
        10 AS section_order,
        n.nspname || '.schema' AS object_order,
        format('CREATE SCHEMA IF NOT EXISTS %I;', n.nspname) AS ddl
    FROM pg_namespace AS n
    JOIN params AS p ON p.selected_schema = n.nspname

    UNION ALL

    /* Enum types */
    SELECT
        20,
        n.nspname || '.' || t.typname,
        format(
            'CREATE TYPE %I.%I AS ENUM (%s);',
            n.nspname,
            t.typname,
            string_agg(quote_literal(e.enumlabel), ', ' ORDER BY e.enumsortorder)
        )
    FROM pg_type AS t
    JOIN pg_namespace AS n ON n.oid = t.typnamespace
    JOIN pg_enum AS e ON e.enumtypid = t.oid
    JOIN params AS p ON p.selected_schema = n.nspname
    GROUP BY n.nspname, t.typname

    UNION ALL

    /* Standalone and serial sequences */
    SELECT
        30,
        n.nspname || '.' || c.relname,
        format(
            E'CREATE SEQUENCE %I.%I\n    AS %s\n    INCREMENT BY %s\n    MINVALUE %s\n    MAXVALUE %s\n    START WITH %s\n    CACHE %s%s;',
            n.nspname,
            c.relname,
            format_type(s.seqtypid, NULL),
            s.seqincrement,
            s.seqmin,
            s.seqmax,
            s.seqstart,
            s.seqcache,
            CASE WHEN s.seqcycle THEN E'\n    CYCLE' ELSE '' END
        )
    FROM pg_class AS c
    JOIN pg_namespace AS n ON n.oid = c.relnamespace
    JOIN pg_sequence AS s ON s.seqrelid = c.oid
    JOIN params AS p ON p.selected_schema = n.nspname
    WHERE c.relkind = 'S'

    UNION ALL

    /* Ordinary tables. Partition definitions require pg_dump for full fidelity. */
    SELECT
        40,
        n.nspname || '.' || c.relname,
        format(
            E'CREATE TABLE %I.%I (\n%s\n);',
            n.nspname,
            c.relname,
            string_agg(
                format(
                    '    %I %s%s%s%s',
                    a.attname,
                    format_type(a.atttypid, a.atttypmod),
                    CASE a.attidentity
                        WHEN 'a' THEN ' GENERATED ALWAYS AS IDENTITY'
                        WHEN 'd' THEN ' GENERATED BY DEFAULT AS IDENTITY'
                        ELSE ''
                    END,
                    CASE
                        WHEN a.attgenerated = 's' THEN
                            format(
                                ' GENERATED ALWAYS AS (%s) STORED',
                                pg_get_expr(ad.adbin, ad.adrelid)
                            )
                        WHEN ad.adbin IS NOT NULL AND a.attidentity = '' THEN
                            format(' DEFAULT %s', pg_get_expr(ad.adbin, ad.adrelid))
                        ELSE ''
                    END,
                    CASE WHEN a.attnotnull THEN ' NOT NULL' ELSE '' END
                ),
                E',\n' ORDER BY a.attnum
            )
        )
    FROM pg_class AS c
    JOIN pg_namespace AS n ON n.oid = c.relnamespace
    JOIN pg_attribute AS a
      ON a.attrelid = c.oid
     AND a.attnum > 0
     AND NOT a.attisdropped
    LEFT JOIN pg_attrdef AS ad
      ON ad.adrelid = a.attrelid
     AND ad.adnum = a.attnum
    JOIN params AS p ON p.selected_schema = n.nspname
    WHERE c.relkind IN ('r', 'p')
    GROUP BY n.nspname, c.relname

    UNION ALL

    /* Sequence ownership, including sequences backing serial columns */
    SELECT
        45,
        sequence_ns.nspname || '.' || sequence_class.relname,
        format(
            'ALTER SEQUENCE %I.%I OWNED BY %I.%I.%I;',
            sequence_ns.nspname,
            sequence_class.relname,
            table_ns.nspname,
            table_class.relname,
            table_attribute.attname
        )
    FROM pg_class AS sequence_class
    JOIN pg_namespace AS sequence_ns ON sequence_ns.oid = sequence_class.relnamespace
    JOIN pg_depend AS dependency
      ON dependency.classid = 'pg_class'::regclass
     AND dependency.objid = sequence_class.oid
     AND dependency.deptype IN ('a', 'i')
    JOIN pg_class AS table_class
      ON table_class.oid = dependency.refobjid
    JOIN pg_namespace AS table_ns ON table_ns.oid = table_class.relnamespace
    JOIN pg_attribute AS table_attribute
      ON table_attribute.attrelid = table_class.oid
     AND table_attribute.attnum = dependency.refobjsubid
    JOIN params AS p ON p.selected_schema = sequence_ns.nspname
    WHERE sequence_class.relkind = 'S'

    UNION ALL

    /* Primary keys, unique constraints, foreign keys and checks */
    SELECT
        50,
        n.nspname || '.' || c.relname || '.' || constraint_row.conname,
        format(
            'ALTER TABLE ONLY %I.%I ADD CONSTRAINT %I %s;',
            n.nspname,
            c.relname,
            constraint_row.conname,
            pg_get_constraintdef(constraint_row.oid, true)
        )
    FROM pg_constraint AS constraint_row
    JOIN pg_class AS c ON c.oid = constraint_row.conrelid
    JOIN pg_namespace AS n ON n.oid = c.relnamespace
    JOIN params AS p ON p.selected_schema = n.nspname
    WHERE constraint_row.contype IN ('p', 'u', 'f', 'c', 'x')

    UNION ALL

    /* Indexes not already created by a table constraint */
    SELECT
        60,
        n.nspname || '.' || index_class.relname,
        pg_get_indexdef(index_class.oid) || ';'
    FROM pg_index AS index_row
    JOIN pg_class AS table_class ON table_class.oid = index_row.indrelid
    JOIN pg_namespace AS n ON n.oid = table_class.relnamespace
    JOIN pg_class AS index_class ON index_class.oid = index_row.indexrelid
    JOIN params AS p ON p.selected_schema = n.nspname
    LEFT JOIN pg_constraint AS constraint_row
      ON constraint_row.conindid = index_row.indexrelid
    WHERE constraint_row.oid IS NULL

    UNION ALL

    /* Functions and procedures */
    SELECT
        70,
        n.nspname || '.' || procedure_row.proname || '.' || procedure_row.oid::text,
        pg_get_functiondef(procedure_row.oid)
    FROM pg_proc AS procedure_row
    JOIN pg_namespace AS n ON n.oid = procedure_row.pronamespace
    JOIN params AS p ON p.selected_schema = n.nspname

    UNION ALL

    /* Views */
    SELECT
        80,
        n.nspname || '.' || c.relname,
        format(
            E'CREATE OR REPLACE VIEW %I.%I AS\n%s;',
            n.nspname,
            c.relname,
            pg_get_viewdef(c.oid, true)
        )
    FROM pg_class AS c
    JOIN pg_namespace AS n ON n.oid = c.relnamespace
    JOIN params AS p ON p.selected_schema = n.nspname
    WHERE c.relkind = 'v'

    UNION ALL

    /* Materialized views */
    SELECT
        85,
        n.nspname || '.' || c.relname,
        format(
            E'CREATE MATERIALIZED VIEW %I.%I AS\n%s\nWITH NO DATA;',
            n.nspname,
            c.relname,
            pg_get_viewdef(c.oid, true)
        )
    FROM pg_class AS c
    JOIN pg_namespace AS n ON n.oid = c.relnamespace
    JOIN params AS p ON p.selected_schema = n.nspname
    WHERE c.relkind = 'm'

    UNION ALL

    /* User-defined triggers */
    SELECT
        90,
        n.nspname || '.' || c.relname || '.' || trigger_row.tgname,
        pg_get_triggerdef(trigger_row.oid, true) || ';'
    FROM pg_trigger AS trigger_row
    JOIN pg_class AS c ON c.oid = trigger_row.tgrelid
    JOIN pg_namespace AS n ON n.oid = c.relnamespace
    JOIN params AS p ON p.selected_schema = n.nspname
    WHERE NOT trigger_row.tgisinternal

    UNION ALL

    /* Row-level security state */
    SELECT
        100,
        n.nspname || '.' || c.relname || '.rls',
        concat_ws(
            E'\n',
            CASE
                WHEN c.relrowsecurity THEN
                    format('ALTER TABLE %I.%I ENABLE ROW LEVEL SECURITY;', n.nspname, c.relname)
            END,
            CASE
                WHEN c.relforcerowsecurity THEN
                    format('ALTER TABLE %I.%I FORCE ROW LEVEL SECURITY;', n.nspname, c.relname)
            END
        )
    FROM pg_class AS c
    JOIN pg_namespace AS n ON n.oid = c.relnamespace
    JOIN params AS p ON p.selected_schema = n.nspname
    WHERE c.relkind IN ('r', 'p')
      AND (c.relrowsecurity OR c.relforcerowsecurity)

    UNION ALL

    /* RLS policies */
    SELECT
        110,
        n.nspname || '.' || c.relname || '.' || policy_row.polname,
        format(
            'CREATE POLICY %I ON %I.%I AS %s FOR %s TO %s%s%s;',
            policy_row.polname,
            n.nspname,
            c.relname,
            CASE WHEN policy_row.polpermissive THEN 'PERMISSIVE' ELSE 'RESTRICTIVE' END,
            CASE policy_row.polcmd
                WHEN 'r' THEN 'SELECT'
                WHEN 'a' THEN 'INSERT'
                WHEN 'w' THEN 'UPDATE'
                WHEN 'd' THEN 'DELETE'
                ELSE 'ALL'
            END,
            policy_roles.role_list,
            CASE
                WHEN policy_row.polqual IS NOT NULL THEN
                    format(' USING (%s)', pg_get_expr(policy_row.polqual, policy_row.polrelid))
                ELSE ''
            END,
            CASE
                WHEN policy_row.polwithcheck IS NOT NULL THEN
                    format(
                        ' WITH CHECK (%s)',
                        pg_get_expr(policy_row.polwithcheck, policy_row.polrelid)
                    )
                ELSE ''
            END
        )
    FROM pg_policy AS policy_row
    JOIN pg_class AS c ON c.oid = policy_row.polrelid
    JOIN pg_namespace AS n ON n.oid = c.relnamespace
    JOIN params AS p ON p.selected_schema = n.nspname
    CROSS JOIN LATERAL (
        SELECT string_agg(
            CASE
                WHEN role_id = 0 THEN 'PUBLIC'
                ELSE quote_ident(role_row.rolname)
            END,
            ', ' ORDER BY role_id
        ) AS role_list
        FROM unnest(policy_row.polroles) AS role_id
        LEFT JOIN pg_roles AS role_row ON role_row.oid = role_id
    ) AS policy_roles
)
SELECT string_agg(
    format(E'-- %s\n%s', object_order, ddl),
    E'\n\n' ORDER BY section_order, object_order
) AS schema_ddl
FROM ddl_parts
WHERE ddl IS NOT NULL
  AND btrim(ddl) <> '';
